function buildCandidate(spec: CandidateSpec, index: number): FictionalCandidate {
  const flavor = CANDIDATE_CATEGORY_FLAVOR[spec.category];
  const initials = spec.displayName
    .split(" ")
    .map((part) => part[0])
    .filter(Boolean)
    .slice(0, 2)
    .join("")
    .toUpperCase();
  const summary = flavor.summaryTemplates[index % flavor.summaryTemplates.length];

  return {
    id: deterministicUuid(`candidate:${spec.slug}`),
    slug: spec.slug,
    displayName: spec.displayName,
    initials,
    headline: `${flavor.headlineSuffix} · ${spec.yearsExperience}+ fictional years of experience`,
    summary,
    location: spec.location,
    yearsExperience: spec.yearsExperience,
    skills: flavor.skills,
    education: spec.education,
    recentRole: spec.recentRole,
    category: spec.category,
    workHistory: [
      {
        role: spec.recentRole,
        company: spec.recentCompany,
        duration: `${Math.max(1, spec.yearsExperience - 2)}–${spec.yearsExperience} simulated years`,
        summary: `Contributed to fictional initiatives at ${spec.recentCompany} within the OfferLoop simulation.`,
      },
    ],
    projects: [
      {
        name: "Simulation Capstone Project",
        description: `A fictional project demonstrating ${flavor.headlineSuffix.toLowerCase()} skills within the OfferLoop simulation.`,
        skills: flavor.skills.slice(0, 3),
      },
    ],
    achievements: flavor.achievements,
    preferredWorkArrangement: spec.preferredWorkArrangement,
    expectedSalaryMin: spec.expectedSalaryMin,
    expectedSalaryMax: spec.expectedSalaryMax,
    availability: spec.availability,
    avatarStyle: {
      gradientFrom: spec.gradient[0],
      gradientTo: spec.gradient[1],
      pattern: spec.pattern,
    },
    isFictional: true,
    isActive: true,
  };
}

export const candidates: FictionalCandidate[] = specs.map(buildCandidate);

export function getCandidateBySlug(slug: string): FictionalCandidate | undefined {
  return candidates.find((candidate) => candidate.slug === slug);
}
