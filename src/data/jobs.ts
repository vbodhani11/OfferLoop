function buildJob(spec: JobSpec, index: number): Job {
  const org = organizations.find((o) => o.slug === spec.orgSlug);
  if (!org) throw new Error(`Unknown organization slug: ${spec.orgSlug}`);
  const flavor = CATEGORY_FLAVOR[spec.category];
  const manager = FICTIONAL_MANAGERS[index % FICTIONAL_MANAGERS.length];
  const benefits = [
    BENEFIT_POOL[index % BENEFIT_POOL.length],
    BENEFIT_POOL[(index + 3) % BENEFIT_POOL.length],
    BENEFIT_POOL[(index + 5) % BENEFIT_POOL.length],
  ];

  return {
    id: deterministicUuid(`job:${spec.slug}`),
    slug: spec.slug,
    organizationId: org.id,
    title: spec.title,
    description: `As a fictional ${spec.title} inside the OfferLoop simulation at ${org.name}, ${flavor.intro}. This role exists only within the OfferLoop simulation and does not represent a real position.`,
    responsibilities: flavor.responsibilities,
    qualifications: flavor.qualifications,
    benefits,
    location: spec.location,
    workArrangement: spec.workArrangement,
    employmentType: spec.employmentType,
    experienceLevel: spec.experienceLevel,
    salaryMin: spec.salaryMin,
    salaryMax: spec.salaryMax,
    signingBonus: spec.signingBonus,
    currency: "USD",
    category: spec.category,
    skills: [...flavor.skills.slice(0, 4), ...(spec.extraSkills ?? [])],
    fictionalManagerName: manager,
    simulatedPostedDaysAgo: spec.postedDaysAgo,
    matchPercentage: spec.matchPercentage,
    isActive: true,
  };
}

export const jobs: Job[] = specs.map(buildJob);

export function getJobBySlug(slug: string): Job | undefined {
  return jobs.find((job) => job.slug === slug);
}

export function getJobById(id: string): Job | undefined {
  return jobs.find((job) => job.id === id);
}

export function getSimilarJobs(job: Job, limit = 3): Job[] {
  return jobs
    .filter(
      (j) =>
        j.id !== job.id &&
        (j.category === job.category || j.organizationId === job.organizationId),
    )
    .slice(0, limit);
}
